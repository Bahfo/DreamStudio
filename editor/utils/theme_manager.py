class ThemeManager(QObject):
    theme_changed = pyqtSignal(str)

    def __init__(self, parent: QObject = None):
        super().__init__(parent)
        self._current_theme: str = "dark"
        self._data: dict = {}
        self._load_theme(self._current_theme)

    def _load_theme(self, name: str) -> None:
        if name == "dark":
            self._data = dict(DARK_COLORS)
        elif name == "light":
            self._data = dict(LIGHT_COLORS)
        elif name == "ocean":
            self._data = dict(OCEAN_COLORS)
        elif name == "solarized_dark":
            self._data = dict(SOLARIZED_DARK_COLORS)
        elif name == "solarized_light":
            self._data = dict(SOLARIZED_LIGHT_COLORS)
        elif name == "Moses":
            self._data = dict(Moses_COLORS)
        elif name == "hacker_blue":
            self._data = dict(HACKER_BLUE_COLORS)
        elif name == "davy":
            self._data = dict(DAVY_COLORS)
        elif name == "high_contrast_dark":
            self._data = dict(HIGH_CONTRAST_DARK_COLORS)
        elif name == "coffee_dark":
            self._data = dict(COFFEE_DARK_COLORS)
        elif name == "coffee_light":
            self._data = dict(COFFEE_LIGHT_COLORS)
        else:
            path = THEME_DIR / f"{name}.json"
            try:
                with open(path, "r", encoding="utf-8") as f:
                    self._data = json.load(f).get("colors", {})
            except (FileNotFoundError, json.JSONDecodeError) as e:
                logger.error(f"Failed to load theme '{name}': {e}")
                self._data = dict(DARK_COLORS)

    def color(self, key: str, fallback: str = "#000000") -> str:
        return self._data.get(key, fallback)

    @property
    def name(self) -> str:
        return self._current_theme

    def switch_to(self, name: str) -> None:
        if name == self._current_theme:
            return
        self._load_theme(name)
        self._current_theme = name
        self.theme_changed.emit(name)
        logger.info("Switched to theme: %s", name)

    def toggle(self) -> str:
        next_theme = "light" if self._current_theme == "dark" else "dark"
        self.switch_to(next_theme)
        return next_theme
