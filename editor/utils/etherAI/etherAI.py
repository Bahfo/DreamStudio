class MainScreen(QFrame):
    """
    Main Ether AI interface.
    """

    send_requested = pyqtSignal()

    def __init__(self, master=None):
        super().__init__(master)
        self._active = False

        self.setFrameShape(QFrame.Shape.NoFrame)
        self.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Expanding)

        self._build_ui()
        self._connect_signals()
        self._build_animations()
        self._apply_default_theme()

    # ------------------------------------------------------------------
    # UI
    # ------------------------------------------------------------------

    def _build_ui(self) -> None:
        self._layout = QVBoxLayout(self)
        self._layout.setContentsMargins(18, 18, 18, 18)

        self._layout.setSpacing(0)

        # --------------------------------------------------------------
        # Header
        # --------------------------------------------------------------

        self.welcome_message = AnimatedGradientLabel("Hi, DreamStudio Developer", self)

        self.welcome_message.setStyleSheet("""
            font-size: 30px;
            font-weight: 600;
            background: transparent;
            """)

        self._layout.addWidget(self.welcome_message)

        self.sub_text = QLabel("Ready to start creating?", self)

        self.sub_text.setObjectName("EtherSubtitle")
        self._layout.addWidget(self.sub_text)

        # --------------------------------------------------------------
        # Flexible space
        # --------------------------------------------------------------

        self._layout.addStretch(1)

        # --------------------------------------------------------------
        # Composer
        # --------------------------------------------------------------

        self.composer = EtherComposer(self)

        self._layout.addWidget(self.composer, 0, Qt.AlignmentFlag.AlignBottom)

        # --------------------------------------------------------------
        # Suggestions
        # --------------------------------------------------------------

        self._layout.addSpacing(24)

        self.features_label = QLabel("Try these prompts first", self)

        self.features_label.setObjectName("EtherSectionTitle")
        self._layout.addWidget(self.features_label)
        self._layout.addSpacing(9)
        self.fix_issues_prompt = EtherSuggestionButton(
            "Review my code in the current file", self
        )
        self.add_documentation_prompt = EtherSuggestionButton(
            "Add documentation to this file's methods and classes", self
        )

        self._layout.addWidget(self.fix_issues_prompt)
        self._layout.addSpacing(7)
        self._layout.addWidget(self.add_documentation_prompt)

        # --------------------------------------------------------------
        # Bottom space
        # --------------------------------------------------------------

        self._layout.addStretch(1)

        # --------------------------------------------------------------
        # Warning
        # --------------------------------------------------------------

        self.warnings_label = QLabel(WARNING_TEXT, self)

        self.warnings_label.setObjectName("EtherWarning")
        self.warnings_label.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.warnings_label.setWordWrap(True)
        self._layout.addWidget(self.warnings_label)

    # ------------------------------------------------------------------
    # Connections
    # ------------------------------------------------------------------

    def _connect_signals(self) -> None:
        self.composer.send_requested.connect(self._on_send)
        self.fix_issues_prompt.clicked.connect(
            lambda: self._use_suggestion(self.fix_issues_prompt.text())
        )
        self.add_documentation_prompt.clicked.connect(
            lambda: self._use_suggestion(self.add_documentation_prompt.text())
        )

    def _on_send(self) -> None:
        prompt = self.composer.prompt.toPlainText().strip()
        if not prompt:
            return

        self.send_requested.emit()

    def _use_suggestion(self, text: str) -> None:
        prompt = self.composer.prompt

        prompt.setPlainText(text)
        prompt.moveCursor(QTextCursor.MoveOperation.End)
        prompt.setFocus()
        QTimer.singleShot(0, prompt._update_height)

    # ------------------------------------------------------------------
    # Animation
    # ------------------------------------------------------------------

    def _build_animations(self) -> None:
        self._subtitle_effect = QGraphicsOpacityEffect(self.sub_text)
        self.sub_text.setGraphicsEffect(self._subtitle_effect)
        self._composer_effect = QGraphicsOpacityEffect(self.composer)
        self.composer.setGraphicsEffect(self._composer_effect)
        self._suggestions_effect = QGraphicsOpacityEffect(self.features_label)
        self.features_label.setGraphicsEffect(self._suggestions_effect)
        self._warning_effect = QGraphicsOpacityEffect(self.warnings_label)
        self.warnings_label.setGraphicsEffect(self._warning_effect)

        self._animations = []

        for effect, duration in (
            (self._subtitle_effect, 260),
            (self._composer_effect, 360),
            (self._suggestions_effect, 420),
            (self._warning_effect, 500),
        ):
            animation = QPropertyAnimation(effect, b"opacity", self)

            animation.setDuration(duration)
            animation.setEasingCurve(QEasingCurve.Type.OutCubic)
            self._animations.append(animation)

    def _animate_in(self) -> None:
        self.welcome_message.start_animation()

        effects = (
            self._subtitle_effect,
            self._composer_effect,
            self._suggestions_effect,
            self._warning_effect,
        )

        for animation, effect in zip(self._animations, effects):
            animation.stop()
            animation.setStartValue(0.0)
            animation.setEndValue(1.0)
            animation.start()

    def _animate_out(self) -> None:
        self.welcome_message.stop_animation()

    # ------------------------------------------------------------------
    # Theme
    # ------------------------------------------------------------------

    def _apply_default_theme(self) -> None:
        self.setStyleSheet("""
            QLabel#EtherSubtitle {
                color: #9AA0A6;
                font-size: 18px;
                background: transparent;
            }

            QLabel#EtherSectionTitle {
                color: palette(text);
                font-size: 17px;
                font-weight: 600;
                background: transparent;
            }

            QLabel#EtherWarning {
                color: #A5A5A5;
                font-size: 11px;
                background: transparent;
            }

            QPushButton#EtherSuggestion {
                text-align: left;
                border: 1px solid palette(mid);
                border-radius: 10px;
                padding: 0px 14px;
                background: transparent;
                color: palette(text);
            }

            QPushButton#EtherSuggestion:hover {
                border: 1px solid palette(highlight);
                background: palette(highlight);
                color: palette(highlightedText);
            }

            QPushButton#EtherSuggestion:pressed {
                border: 1px solid palette(highlight);
                background: palette(mid);
                color: palette(highlightedText);
            }
            """)

        self.composer.set_theme(
            "palette(base)",
            "palette(text)",
            "palette(highlight)",
        )

    def set_theme(self, bg: str, fg: str, sel: str) -> None:
        self.setStyleSheet(f"""
            QLabel#EtherSubtitle {{
                color: {fg};
                font-size: 18px;
                background: transparent;
            }}

            QLabel#EtherSectionTitle {{
                color: {fg};
                font-size: 17px;
                font-weight: 600;
                background: transparent;
            }}

            QLabel#EtherWarning {{
                color: {fg};
                font-size: 11px;
                background: transparent;
            }}

            QPushButton#EtherSuggestion {{
                text-align: left;
                border: 1px solid palette(mid);
                border-radius: 10px;
                padding: 0px 14px;
                background: transparent;
                color: {fg};
            }}

            QPushButton#EtherSuggestion:hover {{
                border: 1px solid palette(highlight);
                background: palette(highlight);
                color: {fg};
            }}

            QPushButton#EtherSuggestion:pressed {{
                border: 1px solid palette(highlight);
                background: palette(mid);
                color: {fg};
            }}
            """)

        self.composer.set_theme(bg, fg, sel)

    # ------------------------------------------------------------------
    # Visibility / activation
    # ------------------------------------------------------------------

    def showEvent(self, event):
        super().showEvent(event)
        QTimer.singleShot(0, self._activate)

    def resizeEvent(self, event):
        super().resizeEvent(event)

        active = event.size().width() > 10
        if active != self._active:
            self._set_active(active)

    def _activate(self) -> None:
        if self.width() > 10:
            self._set_active(True)

    def _set_active(self, active: bool) -> None:
        self._active = active

        if active:
            self._animate_in()
        else:
            self._animate_out()


class EtherAI(PanelShell):
    """
    PanelShell wrapper for Ether AI.
    """

    PANEL_OBJECT_NAME = "EtherAI"
    FRAME_OBJECT_NAME = "EtherAIFrame"
    TITLE_OBJECT_NAME = "EtherAITitle"
    TITLE_TEXT = "Ether AI"

    def __init__(self, parent=None):
        self._ether_screen: MainScreen | None = None

        super().__init__(parent)

        self.setMinimumWidth(450)

    def _build_body(self) -> None:
        self._ether_screen = MainScreen(self)

        self._ether_screen.setSizePolicy(
            QSizePolicy.Policy.Expanding,
            QSizePolicy.Policy.Expanding,
        )

        self._frame_layout.addWidget(self._ether_screen)

    def _header_right_widgets(self) -> list[QWidget]:
        return []

    def set_theme(self, bg: str, fg: str, sel: str) -> None:
        if self._ether_screen is not None:
            self._ether_screen.set_theme(bg, fg, sel)
